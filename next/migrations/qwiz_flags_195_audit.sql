items as (
 select q.*,s.iso2,roster.name_ru,
   (q.solution->>'correct')::integer as answer_index,
   q.solution->>'flag_mode' as flag_mode
 from public.qwiz_bank q join public.qwiz_topics t on t.id=q.topic_id
 cross join lateral (select substring(tag from 5) as iso2 from unnest(q.tags) tag where tag like 'iso:%' limit 1) s
 left join roster on roster.iso2=s.iso2
 where t.name='Флаги мира'
),
issues as (
 select id,iso2,flag_mode,
 case when name_ru is null then 'country_not_in_roster'
      when flag_mode not in ('country','picker') then 'unknown_mechanic'
      when not public.qwiz_flags_question_valid(kind,options,solution) then 'invalid_shape'
      when flag_mode='country' and options->>answer_index is distinct from name_ru then 'wrong_country_option'
      when flag_mode='picker' and solution->'option_labels'->>answer_index is distinct from name_ru then 'wrong_picker_label'
      when flag_mode='country' and solution->>'media_url' not like '%/'||lower(iso2)||'.svg' then 'wrong_source_flag'
      when flag_mode='picker' and options->answer_index->>'image_url' not like '%/'||lower(iso2)||'.svg' then 'wrong_picker_flag'
      when flag_mode='picker' and exists(select 1 from jsonb_array_elements(options) z where z.value ? 'label') then 'leaked_label'
      else null end as issue
 from items
)
select 'total' as audit,count(*)::int as actual,390 as expected from items
union all select 'unique_country_mechanic_pairs',count(*)::int,390 from (select distinct iso2,flag_mode from items) s
union all select 'issue_count',count(*) filter(where issue is not null)::int,0 from issues
union all select 'countries',count(distinct iso2)::int,195 from items
union all select 'published',count(*) filter(where 'fw:published'=any(tags))::int,388 from items
union all select 'on_review',count(*) filter(where 'fw:needs_review'=any(tags))::int,2 from items
order by audit;