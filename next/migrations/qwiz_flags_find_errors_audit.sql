 select b.id,b.options,b.solution from public.qwiz_bank b
 where 'fw:errors-stage6'=any(b.tags)
), classified as (
 select q.id,q.solution->>'correct' as correct, (o.ordinality-1) as idx,
   o.value->>'label' as caption,substring(o.value->>'image_url' from '/([a-z]{2})[.]svg$') as code
 from challenges q, lateral jsonb_array_elements(q.options) with ordinality o(value,ordinality)
), per_question as (
 select id,count(*) as options,
 count(*) filter(where r.code is null) as invalid_country,
 count(*) filter(where r.country is distinct from c.caption) as mismatches,
 max(idx) filter(where r.country is distinct from c.caption) as mismatch_index,
 max(correct::int) as correct
 from classified c left join roster r on r.code=c.code group by id
)
